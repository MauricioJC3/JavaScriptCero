// 9. Promedio de tres números
//    - Escribe una función `promedio(n1, n2, n3)` que devuelva el promedio de tres números.
// fomula:
//                 ∑Valores
// Promedio=  _____________________ 
//             Cantidad de valores 



const promedio = (n1,n2,n3) => {
    return (n1+n2+n3)/3;
}

console.log(promedio(10,5,15));